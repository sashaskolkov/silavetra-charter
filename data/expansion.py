def main():
    # Своё зерно: последовательность не пересекается с generate.py,
    # и правка одного файла не двигает другой.
    rng = generate.random.Random(20260726)

    photos = [p["url"] for p in
              json.load(open(os.path.join(HERE, "photos.source.json")))]

    rows = []
    names = iter(NAMES)

    for area, port, coeff, cruise_count, motor_count in PLACES:
        for kind, count in ((CRUISE, cruise_count), (MOTOR, motor_count)):
            for _ in range(count):
                name = next(names, None)
                if name is None:
                    raise SystemExit(
                        "имена кончились: добавьте их в NAMES в expansion.py"
                    )
                photo = photos[len(rows) % len(photos)]
                row = generate.build_row(
                    rng, name, area, port, coeff, photo,
                    models=MOTOR_HULLS if kind == MOTOR else None,
                )
                rows.append(row[:1] + [kind] + row[1:])

    seen = [r[0] for r in rows]
    duplicates = {n for n in seen if seen.count(n) > 1}
    if duplicates:
        raise SystemExit("дубли имён внутри расширения: %s" % sorted(duplicates))

    with open(TARGET, "w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(COLUMNS)
        writer.writerows(rows)

    areas = len({r[5] for r in rows})
    kinds = {}
    for r in rows:
        kinds[r[1]] = kinds.get(r[1], 0) + 1
    print("expansion.csv: %d лодок, %d акваторий, %s" % (len(rows), areas, kinds))


if __name__ == "__main__":
    main()
