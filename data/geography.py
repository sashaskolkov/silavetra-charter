def resolve(source_region: str) -> tuple[str, str, str]:
    """Разложить «Регион» исходной таблицы на регион, акваторию и порт."""
    if source_region not in AREAS:
        raise KeyError(
            f"акватория «{source_region}» не привязана к региону — "
            f"добавьте её в AREAS в geography.py"
        )
    return AREAS[source_region]


def region_of(area: str) -> str:
    """
    Регион акватории — для строк, где акватория и порт уже названы верно.

    Тем и отличается от resolve: порт не подменяется. Он и не должен —
    у одной акватории портов бывает несколько, как Сортавала и Приозерск
    на Ладоге или Ленск и Якутск на Лене.
    """
    if area in EXPANSION:
        return EXPANSION[area]
    for region, name, _ in AREAS.values():
        if name == area:
            return region
    raise KeyError(
        f"акватория «{area}» не привязана к региону — "
        f"добавьте её в EXPANSION в geography.py"
    )


def check() -> None:
    """Регионы во всех справочниках и в REGION_ORDER должны совпадать до единого."""
    used = {region for region, _, _ in AREAS.values()} | set(EXPANSION.values())
    listed = set(REGION_ORDER)
    if used != listed:
        raise SystemExit(
            f"REGION_ORDER разошёлся со справочниками: "
            f"лишние {sorted(listed - used)}, забытые {sorted(used - listed)}"
        )
    if len(REGION_ORDER) != len(set(REGION_ORDER)):
        raise SystemExit("дубли в REGION_ORDER")

    # Акватория обязана жить в одном регионе. Если имя встречается
    # и в исходной таблице, и в расширении, регионы должны совпасть.
    for area, region in EXPANSION.items():
        for legacy_region, legacy_area, _ in AREAS.values():
            if legacy_area == area and legacy_region != region:
                raise SystemExit(
                    f"акватория «{area}» разошлась по регионам: "
                    f"{legacy_region} в AREAS и {region} в EXPANSION"
                )


if __name__ == "__main__":
    check()
    by_region: dict[str, list[str]] = {region: [] for region in REGION_ORDER}
    for _, (region, area, port) in sorted(AREAS.items()):
        by_region[region].append(f"{area} · {port}")
    for area, region in sorted(EXPANSION.items()):
        by_region[region].append(area)
    for region in REGION_ORDER:
        print(f"\n{region} ({len(by_region[region])})")
        for line in by_region[region]:
            print(f"  {line}")
